'use strict';
const fs=require('fs'),assert=require('assert'),path=require('path');
const server=fs.readFileSync(path.join(__dirname,'server.js'),'utf8');
const app=fs.readFileSync(path.join(__dirname,'public','app.js'),'utf8');
assert.match(server,/ALTER TABLE users ADD COLUMN test_plan TEXT/);
assert.match(server,/test_plan_until/);
assert.ok(server.includes('/test-plan'),'Endpoint de acesso de teste precisa existir.');
assert.ok(server.includes("effective_plan"),'Admin deve devolver plano efetivo.');
assert.ok(server.includes("commercial_plan"),'Sessão deve preservar plano comercial.');
assert.ok(app.includes('adminApplyTestPlan'),'Admin precisa permitir concessão de plano de teste.');
assert.ok(app.includes('adminRemoveTestPlan'),'Admin precisa permitir remoção de plano de teste.');
assert.ok(app.includes("api('/api/admin/stats').catch"),'Falha isolada de estatísticas não pode esvaziar todo o painel.');
assert.ok(app.includes("api('/api/admin/users').catch"),'Falha isolada de usuários não pode quebrar todo o painel.');
assert.ok(!server.includes("datetime('now','-11 months')"),'Estatísticas admin não devem depender de datetime SQLite em PostgreSQL.');
console.log('OK: v134 — painel administrativo resiliente e acesso PRO de teste validados estaticamente.');
